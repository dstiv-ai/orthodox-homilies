// day.js — the Daily Readings page (#/day/YYYY-MM-DD and #/day/today).
// Renders the day's synaxarion entry (title/feast, saints, and a link into
// the library's own "Lives" item when one exists) and the appointed
// readings, each annotated with the St John Chrysostom homily that covers
// it — computed from data/lectionary/chrysostom-map.json (the homily whose
// start is the LAST start <= the reading's start, [chapter, verse]
// lexicographic; start=null entries are introductions and never match).
// The homily links internally to #/item/<id> when data/index.json has an
// item with the matching source_ref ("Homily 56 on Matthew"), else out to
// the public-domain translation on New Advent. Books with no series in the
// map (Mark, Luke, 2 Peter, …) get a plain note — Chrysostom left no
// homily series on them.
//
// Data contract (fixture now, generated full datasets later, same shape):
//   data/lectionary/days/<YYYY>.json — {year, pascha, days:{"YYYY-MM-DD":
//     {titles[], feast_level, fast|null, saints[], readings:[{label, ref,
//     book, from:[c,v], to:[c,v]}]}}}
//   data/lectionary/chrysostom-map.json — {Book: {series, newadvent_base,
//     homilies:[{n, start:[c,v]|null}]}}
//   data/reading-icons.json — {books: {book code: image path}, ot_books:
//     {OT book name: image path}} — the icon beside a reading; a reading
//     with no match renders text-only, with no empty frame.
//   data/lectionary/reading-texts/<date>.json — {date, readings:[{ref,
//     heading, verses[]}]} — generated by scripts/build_reading_texts.py from
//     content/<date>/readings.md's "Easy English" sections, primary readings
//     only. Matched to a day's reading objects by exact `ref` string (dashes
//     normalized); a day with no file, or a reading with no matching ref,
//     renders no disclosure at all.
// Year files load lazily and are cached in memory for the page's lifetime;
// a missing year file or date key renders the graceful "not available"
// state, never a console error.
//
// Rendering: a full-width hero band carries the day's own mosaic cover
// (from data/covers.json via the synaxarion item's cover_key, the same
// lookup js/browse.js does for its row thumbnails), the prev/next arrows,
// the date heading, the feast title(s) and the fast rule. Below it the
// body is one typographic flow — no cards: a quiet "Commemorated:" line,
// an inline "Read the Lives" link, then the primary readings ("At the
// Liturgy" — the large serif reference is the anchor of each entry, with
// its Chrysostom homily note underneath), and only on major feasts a
// quieter "Also Appointed" list of the Vespers/Matins lections. Styles in
// css/day.css.
import { ROOT } from './paths.js';
import { loadIndex } from './catalogue.js';
import { ICON_BOOK_CROSS, ICON_SAINT, ICON_FISH, ICON_CHEVRON_RIGHT, ICON_SCROLL } from './day-icons.js';

const GOSPEL_BOOKS = ['Matt', 'Mark', 'Luke', 'John'];
const NT_BOOKS = new Set(['Matt', 'Mark', 'Luke', 'John', 'Acts', 'Rom', '1Cor', '2Cor', 'Gal', 'Eph', 'Php', 'Col', '1Th', '2Th', '1Tim', '2Tim', 'Titus', 'Phlm', 'Heb', 'Jas', '1Pet', '2Pet', '1Jn', '2Jn', '3Jn', 'Jude', 'Rev']);

let mapPromise = null;
let coversPromise = null;
let readingIconsPromise = null;
const yearPromises = new Map();

function loadChrysostomMap() {
  if (!mapPromise) {
    mapPromise = fetch(`${ROOT}data/lectionary/chrysostom-map.json`)
      .then((res) => (res.ok ? res.json() : {}))
      .catch(() => ({}));
  }
  return mapPromise;
}

// cover_key -> {image, medallion, focus}; used by the hero band.
// Cached for the page's lifetime like the map.
function loadCovers() {
  if (!coversPromise) {
    coversPromise = fetch(`${ROOT}data/covers.json`)
      .then((res) => (res.ok ? res.json() : {}))
      .catch(() => ({}));
  }
  return coversPromise;
}

// book code / OT book name -> icon image path, for the arched plates and
// thumbs beside each reading. Generated from the manifest's
// reading_icon_map by scripts/build_data.py. Cached for the page's
// lifetime like the covers; a missing file means no icons, not an error.
function loadReadingIcons() {
  if (!readingIconsPromise) {
    readingIconsPromise = fetch(`${ROOT}data/reading-icons.json`)
      .then((res) => (res.ok ? res.json() : {}))
      .catch(() => ({}));
  }
  return readingIconsPromise;
}

// date -> {date, readings:[{ref, heading, verses[]}]} | null. One singleton
// promise per date (unlike the map/covers/icons caches above, which are
// global for the page's lifetime) — generated by scripts/build_reading_texts.py;
// a day with no file is the common case, not an error.
const readingTextPromises = new Map();
function loadReadingText(dateStr) {
  if (!readingTextPromises.has(dateStr)) {
    readingTextPromises.set(
      dateStr,
      fetch(`${ROOT}data/lectionary/reading-texts/${dateStr}.json`)
        .then((res) => (res.ok ? res.json() : null))
        .catch(() => null)
    );
  }
  return readingTextPromises.get(dateStr);
}

// Returns the parsed year file, or null when the file is absent / the fetch
// failed — callers treat null as "no data for this year", not as an error.
// Exported for the calendar browser (js/tree.js), which renders the same
// year files as month/day grids.
export function loadYear(year) {
  if (!yearPromises.has(year)) {
    yearPromises.set(
      year,
      fetch(`${ROOT}data/lectionary/days/${year}.json`)
        .then((res) => (res.ok ? res.json() : null))
        .catch(() => null)
    );
  }
  return yearPromises.get(year);
}

export async function loadDay(dateStr) {
  const year = dateStr.slice(0, 4);
  const data = await loadYear(year);
  return data && data.days ? data.days[dateStr] || null : null;
}

function pad2(n) {
  return String(n).padStart(2, '0');
}

// Local (not UTC) date string — "#/day/today" must mean the reader's own day.
function localDateStr(d) {
  return `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`;
}

function shiftDate(dateStr, days) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const dt = new Date(y, m - 1, d + days);
  return localDateStr(dt);
}

function formatDateHeading(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString('en-US', {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });
}

function cmp(a, b) {
  return a[0] - b[0] || a[1] - b[1];
}

// Every homily whose stretch of the book overlaps the reading. A homily's
// stretch runs from its own start to just before the NEXT homily's start —
// so a pericope that straddles a boundary (1 Cor 4:9-16 begins in Homily
// 12's verses but its heart is Homily 13's) lists both, the way the
// library's own Sunday packages pair them. Introductions (start: null)
// never match.
function findHomilies(bookEntry, from, to) {
  const hs = (bookEntry.homilies || []).filter((h) => h.start);
  const found = [];
  hs.forEach((h, i) => {
    const next = i + 1 < hs.length ? hs[i + 1].start : null;
    const overlaps = cmp(h.start, to || from) <= 0 && (!next || cmp(next, from) > 0);
    if (overlaps) found.push(h);
  });
  return found;
}

// "Homilies on Matthew" -> "Matthew"; "Commentary on Galatians" -> "Galatians"
// — the book's name as it appears in a source_ref like "Homily 56 on Matthew".
function seriesBookName(series) {
  return String(series).replace(/^(?:Homilies|Commentary) on /, '');
}

function el(tag, className, html) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (html !== undefined) node.innerHTML = html;
  return node;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function text(tag, className, value) {
  const node = el(tag, className);
  node.textContent = value;
  return node;
}

